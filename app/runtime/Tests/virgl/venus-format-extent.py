#!/usr/bin/env python3
"""src/venus/vkr_format_extent.h of virgl-venus-copy-regions.patch: the format facts vkr's
copy checks need besides vkr_format_table.h (texel block extent, the planes of multi-planar
formats, the bytes a depth or stencil texel takes in a buffer) for every VkFormat that both
the Vulkan registry (vk.xml) and the vulkan_core.h vkr is built with know.
   venus-format-extent.py VK_XML VULKAN_CORE_H > vkr_format_extent.h"""
import re
import sys
import xml.etree.ElementTree as ET

xml, header = sys.argv[1:3]
known = set(re.findall(r"^\s+(VK_FORMAT_\w+) = \d+,", open(header).read(), re.M))
extents, planes, depth = {}, {}, {}
count = 0
for f in ET.parse(xml).getroot().iter("format"):
    name = f.get("name")
    if name not in known:
        continue
    count += 1
    w, h, _ = (int(v) for v in (f.get("blockExtent") or "1,1,1").split(","))
    if (w, h) != (1, 1):
        extents.setdefault((w, h), []).append(name)
    p = tuple((int(q.get("index")), int(q.get("widthDivisor")), int(q.get("heightDivisor")),
               q.get("compatible")) for q in f.findall("plane"))
    if len(p) > 1:
        planes.setdefault(p, []).append(name)
    for c in f.findall("component"):
        if c.get("name") == "D":
            # a depth texel in a buffer: D16 2 bytes, D24 and D32 4 bytes (Vulkan spec,
            # "Copying Data Between Buffers and Images")
            depth.setdefault(2 if int(c.get("bits")) == 16 else 4, []).append(name)


def cases(names, indent="   "):
    out, line = [], indent
    for n in sorted(names):
        item = f"case {n}:"
        if len(line) + len(item) + 1 > 96 and line.strip():
            out.append(line.rstrip())
            line = indent
        line += item + " "
    out.append(line.rstrip())
    return "\n".join(out)


print("/* OmacVM (virgl-venus-copy-regions.patch): generated by app/runtime/Tests/virgl/")
print(" * venus-format-extent.py from the Vulkan registry (vk.xml) and venus-protocol/vulkan_core.h.")
print(" * Do not edit; run the script again. */\n")
print("#ifndef VKR_FORMAT_EXTENT_H\n#define VKR_FORMAT_EXTENT_H\n")
print('#include "vkr_common.h"\n')
print("/* the texel block's width and height in texels (1 x 1 for most formats) */")
print("static inline VkExtent2D\nvkr_format_block_extent(VkFormat format)\n{\n   switch (format) {")
for (w, h) in sorted(extents):
    print(cases(extents[(w, h)]))
    print(f"      return (VkExtent2D){{ {w}, {h} }};")
print("   default:\n      return (VkExtent2D){ 1, 1 };\n   }\n}\n")
print("/* plane `plane` of a multi-planar format: its format and how much smaller than the image it")
print(" * is; VK_FORMAT_UNDEFINED for a plane the format does not have */")
print("static inline VkFormat\nvkr_format_plane(VkFormat format, uint32_t plane, uint32_t *width_divisor,")
print("                 uint32_t *height_divisor)\n{\n   *width_divisor = *height_divisor = 1;")
print("   switch (format) {")
for p in sorted(planes):
    print(cases(planes[p]))
    print("      switch (plane) {")
    for index, wd, hd, compat in p:
        print(f"      case {index}:")
        if (wd, hd) != (1, 1):
            print(f"         *width_divisor = {wd};\n         *height_divisor = {hd};")
        print(f"         return {compat};")
    print("      default:\n         return VK_FORMAT_UNDEFINED;\n      }")
print("   default:\n      return VK_FORMAT_UNDEFINED;\n   }\n}\n")
print("/* the bytes a depth texel of a depth format takes in a buffer; 0 for other formats (a")
print(" * stencil texel always takes 1) */")
print("static inline uint32_t\nvkr_format_depth_copy_size(VkFormat format)\n{\n   switch (format) {")
for size in sorted(depth):
    print(cases(depth[size]))
    print(f"      return {size};")
print("   default:\n      return 0;\n   }\n}")
print(f"\n/* {count} formats */\n#endif /* VKR_FORMAT_EXTENT_H */")
