#!/usr/bin/env python3
"""src/venus/vkr_proc_entries.h of virgl-venus-missing-entries.patch: every member of
vn_physical_device_proc_table and vn_device_proc_table (venus-protocol's
vn_protocol_renderer_util.h) with its PFN's return type and parameters (the Vulkan headers
in venus-protocol), and what its stub returns. vkr_missing_entries.c makes a stub of the
entry's own type from each line.
   venus-missing-entries.py SRC_VENUS_DIR > vkr_proc_entries.h
run-venus-limits.py runs it on the built tree and fails when the header differs."""
import re
import sys
from pathlib import Path

proto = Path(sys.argv[1]) / "venus-protocol"
util = (proto / "vn_protocol_renderer_util.h").read_text()

pfns = {}
for header in ("vulkan_core.h", "vulkan_metal.h", "vulkan_beta.h"):
    for ret, name, params in re.findall(
            r"^typedef (.+?) \(VKAPI_PTR \*(PFN_vk\w+)\)\((.*)\);$",
            (proto / header).read_text(), re.M):
        pfns[name] = (ret.strip(), re.sub(r"\s+", " ", params.strip()))

# what a stub returns (vkr's own callers then fail cleanly); a new return type stops here
FALLBACK = {"VkResult": "VK_ERROR_FEATURE_NOT_PRESENT", "VkBool32": "VK_FALSE",
            "uint32_t": "0", "uint64_t": "0", "VkDeviceAddress": "0", "VkDeviceSize": "0",
            "PFN_vkVoidFunction": "NULL"}


def table(name):
    body = re.search(r"^struct %s \{\n(.*?)^\};" % name, util, re.M | re.S)
    if not body:
        sys.exit(f"{name}: not in vn_protocol_renderer_util.h")
    lines = []
    for pfn, member in re.findall(r"^\s+(PFN_vk\w+) (\w+);$", body.group(1), re.M):
        if pfn not in pfns:
            sys.exit(f"{name}.{member}: no typedef of {pfn} in the Vulkan headers")
        ret, params = pfns[pfn]
        if params == "void":
            sys.exit(f"{name}.{member}: no parameters")
        if ret == "void":
            lines.append(f"   V({member}, ({params}))")
        elif ret in FALLBACK:
            lines.append(f"   X({ret}, {member}, ({params}), {FALLBACK[ret]})")
        else:
            sys.exit(f"{name}.{member}: no fallback for the return type {ret}")
    if len(body.group(1).strip().splitlines()) != len(lines):
        sys.exit(f"{name}: a member that is not a PFN")
    return lines


tables = [("PHYSICAL_DEVICE", table("vn_physical_device_proc_table")),
          ("DEVICE", table("vn_device_proc_table"))]
names = [line.split("(")[1].split(",")[0 if line.startswith("   V") else 1].strip()
         for _, lines in tables for line in lines]
if len(names) != len(set(names)):
    sys.exit("an entry in both tables: one stub would be defined twice")

print("/* Generated by app/runtime/Tests/virgl/venus-missing-entries.py from")
print(" * venus-protocol/vn_protocol_renderer_util.h and the Vulkan headers (OmacVM,")
print(" * virgl-venus-missing-entries.patch); do not edit. Every proc table entry: X(return")
print(" * type, name, parameters, what its stub returns), or V(name, parameters) when it")
print(" * returns nothing. */")
print("#ifndef VKR_PROC_ENTRIES_H")
print("#define VKR_PROC_ENTRIES_H")
for kind, lines in tables:
    print()
    print(f"#define VKR_{kind}_PROC_ENTRY_COUNT {len(lines)}")
    print(f"#define VKR_{kind}_PROC_ENTRIES(X, V) \\")
    print(" \\\n".join(lines))
print()
print("#endif /* VKR_PROC_ENTRIES_H */")
