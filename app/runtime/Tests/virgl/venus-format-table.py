#!/usr/bin/env python3
"""src/venus/vkr_format_table.h of virgl-venus-image-limits.patch: the format facts vkr's
image and view checks need (texel block size, plane count, depth/stencil aspects) for every
VkFormat that both the Vulkan registry (vk.xml) and the vulkan_core.h vkr is built with know.
   venus-format-table.py VK_XML VULKAN_CORE_H > vkr_format_table.h"""
import re
import sys
import xml.etree.ElementTree as ET

xml, header = sys.argv[1:3]
known = set(re.findall(r"^\s+(VK_FORMAT_\w+) = \d+,", open(header).read(), re.M))
sizes, planes, depth, stencil = {}, {}, set(), set()
for f in ET.parse(xml).getroot().iter("format"):
    name = f.get("name")
    if name not in known:
        continue
    sizes.setdefault(int(f.get("blockSize")), []).append(name)
    n = len(f.findall("plane"))
    if n > 1:
        planes.setdefault(n, []).append(name)
    comps = {c.get("name") for c in f.findall("component")}
    if "D" in comps:
        depth.add(name)
    if "S" in comps:
        stencil.add(name)


def cases(names, indent="   "):
    out, line = [], indent
    for n in sorted(names):
        item = f"case {n}:"
        if len(line) + len(item) + 1 > 96 and line.strip():
            out.append(line.rstrip())
            line = indent
        line += item + " "
    out.append(line.rstrip())
    return "\n".join(out)


print("/* OmacVM (virgl-venus-image-limits.patch): generated by app/runtime/Tests/virgl/")
print(" * venus-format-table.py from the Vulkan registry (vk.xml) and venus-protocol/vulkan_core.h.")
print(" * Do not edit; run the script again. */\n")
print("#ifndef VKR_FORMAT_TABLE_H\n#define VKR_FORMAT_TABLE_H\n")
print('#include "vkr_common.h"\n')
print("/* the texel block size in bytes; 0 for a format this table does not know */")
print("static inline uint32_t\nvkr_format_block_size(VkFormat format)\n{\n   switch (format) {")
for size in sorted(sizes):
    print(cases(sizes[size]))
    print(f"      return {size};")
print("   default:\n      return 0;\n   }\n}\n")
print("/* 2 or 3 for a multi-planar format, else 1 */")
print("static inline uint32_t\nvkr_format_plane_count(VkFormat format)\n{\n   switch (format) {")
for n in sorted(planes):
    print(cases(planes[n]))
    print(f"      return {n};")
print("   default:\n      return 1;\n   }\n}\n")
print("/* DEPTH and/or STENCIL for a depth/stencil format, else COLOR */")
print("static inline VkImageAspectFlags\nvkr_format_aspects(VkFormat format)\n{\n   switch (format) {")
for group, flags in ((depth & stencil, "VK_IMAGE_ASPECT_DEPTH_BIT | VK_IMAGE_ASPECT_STENCIL_BIT"),
                     (depth - stencil, "VK_IMAGE_ASPECT_DEPTH_BIT"),
                     (stencil - depth, "VK_IMAGE_ASPECT_STENCIL_BIT")):
    print(cases(group))
    print(f"      return {flags};")
print("   default:\n      return VK_IMAGE_ASPECT_COLOR_BIT;\n   }\n}")
known_in_xml = sum(len(v) for v in sizes.values())
print(f"\n/* {known_in_xml} formats */\n#endif /* VKR_FORMAT_TABLE_H */")
